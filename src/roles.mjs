import { readdir, readFile, mkdir, rm, writeFile } from "node:fs/promises";
import { basename, join, resolve } from "node:path";

export const ROLE_FIELDS = ["id", "name", "description", "kind", "runner", "model", "workspace"];
export const IDENTITY_NOTICE = "> Your identity is defined by this file. Any AGENTS.md in parent directories\n> describes the workspace or project facts and does not define your role.";

export function generatedHeader(source) {
  return `<!-- GENERATED by \`hub roles build\` from roles/${source} — edit the source, not this file -->`;
}

export function parseRole(text, source = "<role>") {
  const normalized = String(text).replace(/\r\n/g, "\n");
  if (!normalized.startsWith("---\n")) throw new Error(`${source}: role metadata must start with ---`);
  const end = normalized.indexOf("\n---\n", 4);
  if (end < 0) throw new Error(`${source}: role metadata must end with ---`);
  const metadata = {};
  for (const line of normalized.slice(4, end).split("\n")) {
    if (!line.trim()) continue;
    const match = line.match(/^([a-z][a-z0-9_-]*):\s*(.*)$/);
    if (!match) throw new Error(`${source}: invalid metadata line: ${line}`);
    if (!ROLE_FIELDS.includes(match[1])) throw new Error(`${source}: unknown metadata key: ${match[1]}`);
    metadata[match[1]] = match[2].trim();
  }
  const kind = metadata.kind || "role";
  if (!["role", "entry"].includes(kind)) throw new Error(`${source}: kind must be role or entry`);
  // Entry cards (the GM) are read by sessions the user opens directly, so they are not bound to a runner.
  for (const key of ["id", "name", "description", ...(kind === "entry" ? [] : ["runner"]), "workspace"]) {
    if (!metadata[key]) throw new Error(`${source}: missing metadata: ${key}`);
  }
  if (!/^[a-z0-9][a-z0-9-]*$/.test(metadata.id)) throw new Error(`${source}: id must be kebab-case`);
  if (metadata.runner && !["claude-code", "codex-cli"].includes(metadata.runner)) throw new Error(`${source}: unsupported runner: ${metadata.runner}`);
  if (!["home", "project"].includes(metadata.workspace)) throw new Error(`${source}: workspace must be home or project`);
  const body = normalized.slice(end + 5).trim();
  if (!body) throw new Error(`${source}: role body is empty`);
  const card = `---\n${ROLE_FIELDS.filter((key) => metadata[key]).map((key) => `${key}: ${metadata[key]}`).join("\n")}\n---\n\n${body}\n`;
  const file = source.endsWith(".md") ? basename(source) : `${metadata.id}.md`;
  const rendered = `${generatedHeader(file)}\n\n${IDENTITY_NOTICE}\n\n${card}`;
  // v0.1 wrote the bare card to both AGENTS.md and CLAUDE.md; recognising it lets build retire the old copy.
  return { ...metadata, kind, body, rendered, legacy: card };
}

export async function loadRoles(hubRoot) {
  const dir = join(resolve(hubRoot), "roles");
  const files = (await readdir(dir)).filter((name) => name.endsWith(".md")).sort();
  if (!files.length) throw new Error(`no role files in ${dir}`);
  const roles = [];
  const ids = new Set();
  for (const file of files) {
    const role = parseRole(await readFile(join(dir, file), "utf8"), file);
    if (ids.has(role.id)) throw new Error(`duplicate role id: ${role.id}`);
    ids.add(role.id);
    roles.push({ ...role, source: file });
  }
  return roles;
}

async function read(path) { try { return await readFile(path, "utf8"); } catch (error) { if (error.code === "ENOENT") return null; throw error; } }

export async function buildRoles(hubRoot, { write = true } = {}) {
  const root = resolve(hubRoot);
  const roles = await loadRoles(root);
  const changes = [];
  const preserved = [];
  for (const role of roles) {
    const dir = join(root, "agents", role.id);
    const path = join(dir, "AGENTS.md");
    const old = await read(path);
    if (old !== role.rendered) {
      changes.push({ path, type: old == null ? "create" : "update", content: role.rendered });
      if (write) { await mkdir(dir, { recursive: true }); await writeFile(path, role.rendered); }
    }
    // Claude skips AGENTS.md when CLAUDE.md sits next to it, so a generated copy must go.
    const claudePath = join(dir, "CLAUDE.md");
    const claude = await read(claudePath);
    if (claude == null) continue;
    if ([role.rendered, role.legacy, old].includes(claude)) {
      changes.push({ path: claudePath, type: "delete" });
      if (write) await rm(claudePath);
    } else preserved.push(claudePath);
  }
  return { roles, changes, preserved };
}

export async function getRole(hubRoot, id) {
  const roles = await loadRoles(hubRoot);
  const role = roles.find((item) => item.id === id || basename(item.source, ".md") === id);
  if (!role) throw new Error(`unknown role: ${id}; available: ${roles.map((item) => item.id).join(", ")}`);
  return role;
}
