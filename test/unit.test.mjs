test("installer deletes locked legacy role CLAUDE.md copies unless they were edited", async () => {
  const { hub, project } = await fixture();
  await writeFile(join(hub, "roles", "qa.md"), roleText("qa"));
  await writeFile(join(project, "AGENTS.md"), "# P\n");
  await install({ hub, project });
  const lockPath = join(project, ".agenthub/install.lock.json");
  const lock = JSON.parse(await readFile(lockPath, "utf8"));
  const legacy = "legacy generated copy\n";
  const { createHash } = await import("node:crypto");
  for (const id of ["dev", "qa"]) {
    await writeFile(join(project, `agents/${id}/CLAUDE.md`), legacy);
    lock.files[`agents/${id}/CLAUDE.md`] = { sha256: createHash("sha256").update(legacy).digest("hex"), mode: "file" };
  }
  await writeFile(lockPath, `${JSON.stringify(lock, null, 2)}\n`);
  await writeFile(join(project, "agents/qa/CLAUDE.md"), "edited by hand\n");
  const plan = await install({ hub, project });
  assert.deepEqual(plan.operations.filter((item) => item.type === "delete").map((item) => item.rel), ["agents/dev/CLAUDE.md"]);
  assert.deepEqual(plan.preserved.map((item) => item.rel), ["agents/qa/CLAUDE.md"]);
  assert.equal(await exists(join(project, "agents/dev/CLAUDE.md")), false);
  assert.equal(await readFile(join(project, "agents/qa/CLAUDE.md"), "utf8"), "edited by hand\n");
  const after = JSON.parse(await readFile(lockPath, "utf8"));
  assert.equal(Object.keys(after.files).some((rel) => rel.endsWith("CLAUDE.md")), false, "preserved files are no longer tracked");
  assert.equal((await install({ hub, project })).operations.length, 0);
});

