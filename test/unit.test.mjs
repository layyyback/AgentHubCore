test("porcelain and plain snapshots classify changes", async () => {
  assert.deepEqual(parsePorcelainZ(Buffer.from(" M a.txt\0?? b.txt\0")), [{ status: " M", path: "a.txt", origPath: null }, { status: "??", path: "b.txt", origPath: null }]);
  const root = await mkdtemp(join(tmpdir(), "snapshot-"));
  await writeFile(join(root, "old.txt"), "one\n");
  const before = await captureSnapshot(root, { forcePlain: true });
  await writeFile(join(root, "old.txt"), "two\n"); await writeFile(join(root, "new.txt"), "new\n");
  const after = await captureSnapshot(root, { forcePlain: true });
  const diff = diffSnapshots(before, after);
  assert.deepEqual(diff.added, ["new.txt"]); assert.deepEqual(diff.modified, ["old.txt"]);
  const beforeDelete = await captureSnapshot(root, { forcePlain: true });
  const { rm } = await import("node:fs/promises"); await rm(join(root, "new.txt"));
  assert.deepEqual(diffSnapshots(beforeDelete, await captureSnapshot(root, { forcePlain: true })).deleted, ["new.txt"]);
});

